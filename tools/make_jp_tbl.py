"""make_jp_tbl.py: write tbl/jp.tbl, the game's text table (Shift-JIS plus its ASCII control codes).

    python -X utf8 tools/make_jp_tbl.py          # (re)writes tbl/jp.tbl; tests/test_extract.py checks it is current

The game's text is plain cp932 (docs/re/text.md). The table holds:
- the control codes `#0` {br}, `#4` {wait}, `#5` {spk} (2 ASCII digits follow), `#2` {face} (5 ASCII digits follow);
  tools/text.py folds the digits into `{spk:NN}` / `{face:NNNNN}`;
- printable ASCII except `[ ] { }` (the codec's escape characters; the ROM's text has none of them);
- half-width katakana A1-DF;
- every two-byte cp932 code that decodes and re-encodes to itself (non-canonical duplicates, e.g. the NEC/IBM
  copies, are left out so they decode as [XX] escapes and still roundtrip).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "tbl" / "jp.tbl"

CONTROLS = [("2330", "{br}"), ("2334", "{wait}"), ("2335", "{spk}"), ("2332", "{face}")]


def lines():
    out = ["# Toyrobo Force text table, generated by tools/make_jp_tbl.py: do not edit by hand."]
    out += [f"{k}={v}" for k, v in CONTROLS]
    for b in range(0x20, 0x7F):
        c = chr(b)
        if c not in "[]{}":
            out.append(f"{b:02X}=" + (r"\s" if c == " " else c))
    for b in range(0xA1, 0xE0):
        out.append(f"{b:02X}=" + bytes([b]).decode("cp932"))
    for lead in list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD)):
        for trail in list(range(0x40, 0x7F)) + list(range(0x80, 0xFD)):
            code = bytes([lead, trail])
            try:
                ch = code.decode("cp932")
            except UnicodeDecodeError:
                continue
            if ch.encode("cp932") == code:
                out.append(f"{code.hex().upper()}={ch}")
    return out


def text():
    return "\n".join(lines()) + "\n"


def main():
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text(), encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(lines()) - 1} entries")


if __name__ == "__main__":
    main()
