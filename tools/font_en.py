WIDTH, HEIGHT = 5, 9


def _load():
    out = {" ": [0] * HEIGHT}
    for line in _GLYPHS.strip("\n").split("\n"):
        ch, *rows = line.split(" ")
        if len(ch) != 1 or len(rows) != HEIGHT or any(len(r) != WIDTH or set(r) - set("#.") for r in rows):
            raise ValueError(f"font_en: bad glyph line {line!r}")
        if ch in out:
            raise ValueError(f"font_en: {ch!r} defined twice")
        out[ch] = [sum(1 << (WIDTH - 1 - x) for x, c in enumerate(r) if c == "#") for r in rows]
    return out


GLYPHS = _load()  # char -> HEIGHT row bitmasks, bit WIDTH-1 = leftmost pixel
